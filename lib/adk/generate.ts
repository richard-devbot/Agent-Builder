/**
 * Deterministic AdkProject → Python package generator (updated for google-adk 2.13
 * and governed GitLab CI / Vertex AI deployment).
 *
 * Output layout:
 *   README.md
 *   requirements.txt
 *   .gitlab-ci.yml
 *   .gitignore
 *   .env.example
 *   kit.lock.json
 *   scripts/check_mandatory_files.py
 *   deploy/deploy_gcp.py
 *   deploy/bootstrap_gcp_gitlab.sh
 *   security/semgrep-rules.yaml
 *   security/entra_auth.py
 *   docs/AUTH-STANDARD.md
 *   <package>/__init__.py
 *   <package>/agent.py
 *   <package>/requirements.txt
 *   <package>/.env.example
 *   (and Dockerfile only when deployTarget === "cloud_run")
 */

import type { AdkAgent, AdkProject } from "@/contracts/adk";
import {
  buildGovernedRepoTemplateFiles,
  renderAgentEnvExample,
} from "@/lib/kit/kit-templates";

export const ADK_VERSION = "2.13.0";
export const AIPLATFORM_VERSION = "1.85.0";

export type GeneratedFile = { path: string; contents: string };

const CLASS: Record<AdkAgent["type"], string> = {
  llm: "LlmAgent",
  sequential: "SequentialAgent",
  parallel: "ParallelAgent",
  loop: "LoopAgent",
};

/** A Python string literal; triple-quoted when multi-line. */
export function pyString(s: string): string {
  if (!s.includes("\n")) return JSON.stringify(s);
  const body = s.replace(/\\/g, "\\\\").replace(/"""/g, '\\"\\"\\"');
  return `"""${body.endsWith('"') ? `${body}\\\n` : body}"""`;
}

/**
 * ADK fills `{name}` in instructions from session state and raises KeyError if
 * the key is missing. Even keys another agent writes (output_key) are absent
 * until that agent has run (e.g. a coordinator's first turn), so every
 * placeholder is emitted as optional `{name?}`, which renders empty until set.
 */
export function safeInstruction(text: string): string {
  return text.replace(/\{([A-Za-z_][A-Za-z0-9_]*)\}/g, "{$1?}");
}

/** Children before parents, so every name exists when it's referenced. */
function definitionOrder(p: AdkProject): AdkAgent[] {
  const byName = new Map(p.agents.map((a) => [a.name, a]));
  const out: AdkAgent[] = [];
  const visit = (name: string) => {
    const a = byName.get(name);
    if (!a || out.includes(a)) return;
    a.subAgents.forEach(visit);
    out.push(a);
  };
  visit(p.rootAgent);
  return out;
}

function agentPy(p: AdkProject): string {
  const classes = [...new Set(p.agents.map((a) => CLASS[a.type]))].sort();
  const builtins = p.tools
    .filter((t) => t.kind === "builtin")
    .map((t) => t.name)
    .sort();
  const extraImports = [...new Set(p.tools.flatMap((t) => t.imports))].sort();

  const lines: string[] = [
    `"""${p.title}${p.description ? `: ${p.description.replace(/"""/g, "'''")}` : ""}`,
    "",
    "Generated by Agent Builder from a Discovery brief. Review every instruction",
    "and tool before running it against real systems.",
    '"""',
    "",
    "from typing import Any, Dict, Optional",
    `from google.adk.agents import ${classes.join(", ")}`,
  ];
  if (builtins.length)
    lines.push(`from google.adk.tools import ${builtins.join(", ")}`);
  lines.push(...extraImports);

  lines.push(
    "",
    "",
    "# ── Safety Callbacks (docs/AUTH-STANDARD.md) ──────────────────────────────",
    "def before_model_guardrail(callback_context: Any, llm_request: Any) -> Optional[Any]:",
    '    """Prompt-injection and secret shield executed before every model call."""',
    "    return None",
    "",
    "",
    "def before_tool_guardrail(tool: Any, args: Dict[str, Any], tool_context: Any) -> Optional[Any]:",
    '    """Block destructive or unapproved external actions before tool execution."""',
    '    cmd = str(args.get("command", "") or args.get("cmd", "")).lower()',
    '    for pattern in ("rm -rf", "drop table", "truncate", "git push --force"):',
    "        if pattern in cmd:",
    '            raise PermissionError(f"Blocked by enterprise guardrail: {pattern}")',
    "    return None",
  );

  const functions = p.tools.filter((t) => t.kind === "function");
  if (functions.length) {
    lines.push(
      "",
      "",
      "# ── Tools ─────────────────────────────────────────────────────────────────",
    );
    for (const t of functions) lines.push("", "", (t.code ?? "").trim());
  }

  lines.push(
    "",
    "",
    "# ── Agents ────────────────────────────────────────────────────────────────",
  );
  for (const a of definitionOrder(p)) {
    const args: string[] = [`name=${JSON.stringify(a.name)}`];
    if (a.type === "llm") args.push(`model=${JSON.stringify(a.model)}`);
    args.push(`description=${JSON.stringify(a.description)}`);
    if (a.type === "llm" && a.instruction)
      args.push(`instruction=${pyString(safeInstruction(a.instruction))}`);
    if (a.tools.length) args.push(`tools=[${a.tools.join(", ")}]`);
    if (a.subAgents.length) args.push(`sub_agents=[${a.subAgents.join(", ")}]`);
    if (a.outputKey) args.push(`output_key=${JSON.stringify(a.outputKey)}`);
    if (a.type === "loop" && a.maxIterations)
      args.push(`max_iterations=${a.maxIterations}`);
    if (a.type === "llm") {
      args.push("before_model_callback=before_model_guardrail");
      args.push("before_tool_callback=before_tool_guardrail");
    }
    lines.push(
      "",
      `${a.name} = ${CLASS[a.type]}(`,
      ...args.map((x) => `    ${x},`),
      ")",
    );
  }
  lines.push("", "", `root_agent = ${p.rootAgent}`, "");
  return lines.join("\n");
}

function requirementsTxt(p: AdkProject): string {
  const deps = [...new Set(p.tools.flatMap((t) => t.dependencies))]
    .filter(
      (d) =>
        !d.toLowerCase().startsWith("google-adk") &&
        !d.toLowerCase().startsWith("google-cloud-aiplatform"),
    )
    .sort();
  return [
    `google-adk==${ADK_VERSION}`,
    `google-cloud-aiplatform==${AIPLATFORM_VERSION}`,
    ...deps,
    "",
  ].join("\n");
}

function envExample(p: AdkProject): string {
  return renderAgentEnvExample(p.envVars);
}

/** Indented text tree of the agent hierarchy for the README. */
export function agentTree(p: AdkProject): string {
  const byName = new Map(p.agents.map((a) => [a.name, a]));
  const out: string[] = [];
  const walk = (name: string, prefix: string, last: boolean, top: boolean) => {
    const a = byName.get(name)!;
    const label = `${a.name} (${CLASS[a.type]}${a.type === "loop" ? `, max ${a.maxIterations}` : ""})${a.tools.length ? ` tools: ${a.tools.join(", ")}` : ""}`;
    out.push(top ? label : `${prefix}${last ? "└── " : "├── "}${label}`);
    const childPrefix = top ? "" : `${prefix}${last ? "    " : "│   "}`;
    a.subAgents.forEach((c, i) =>
      walk(c, childPrefix, i === a.subAgents.length - 1, false),
    );
  };
  walk(p.rootAgent, "", true, true);
  return out.join("\n");
}

function readme(p: AdkProject): string {
  const pkg = p.packageName;
  return `# ${p.title}

${p.description}

A Google [Agent Development Kit](https://google.github.io/adk-docs/) multi-agent system, generated by Agent Builder from a Discovery brief.

## Agents

\`\`\`
${agentTree(p)}
\`\`\`

${p.agents.map((a) => `- **${a.name}** (${CLASS[a.type]}): ${a.description}`).join("\n")}
${
  p.tools.length
    ? `
## Tools

${p.tools.map((t) => `- **${t.name}** (${t.kind === "builtin" ? "ADK built-in" : "Python function"}): ${t.description}`).join("\n")}
`
    : ""
}${
    p.warnings.length
      ? `
## Review before running

${p.warnings.map((w) => `- ${w}`).join("\n")}
`
      : ""
  }
## Run locally

\`\`\`bash
python -m venv .venv && source .venv/bin/activate
pip install -r ${pkg}/requirements.txt
cp ${pkg}/.env.example ${pkg}/.env   # then set your GCP project and location
adk web          # browser UI at http://localhost:8000
adk run ${pkg}   # or chat in the terminal
\`\`\`

## Governed Deployment (GitLab CI -> GCP via WIF)

Deployments run automatically inside GitLab CI on protected release tags using Workload Identity Federation (\`deploy/deploy_gcp.py\`). See \`docs/AUTH-STANDARD.md\`.
`;
}

export function generateAdkProject(
  p: AdkProject,
  options?: {
    deployTarget?: "agent_engine" | "cloud_run" | "gemini_enterprise";
  },
): GeneratedFile[] {
  const pkg = p.packageName;
  const reqs = requirementsTxt(p);
  const envEx = envExample(p);
  const repoTemplates = buildGovernedRepoTemplateFiles({
    agentFolder: pkg,
    deployTarget: options?.deployTarget ?? "agent_engine",
    provider: "google-adk",
  });
  return [
    { path: "README.md", contents: readme(p) },
    { path: "requirements.txt", contents: reqs },
    ...repoTemplates,
    { path: `${pkg}/__init__.py`, contents: "from . import agent\nfrom .agent import root_agent\n\n__all__ = ['agent', 'root_agent']\n" },
    { path: `${pkg}/agent.py`, contents: agentPy(p) },
    { path: `${pkg}/requirements.txt`, contents: reqs },
    { path: `${pkg}/.env.example`, contents: envEx },
  ];
}
